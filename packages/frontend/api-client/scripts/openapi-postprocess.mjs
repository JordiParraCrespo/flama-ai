import { execSync } from 'node:child_process';
import * as fs from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const apiServicesFolder = path.resolve(__dirname, '../src/data-access/api/openapi');
const indexFilePath = path.join(apiServicesFolder, 'index.ts');
const generatedTypesPath = path.resolve(__dirname, '../src/generated/types.gen.ts');

const BANNER = '/* Auto-generated by openapi-postprocess -- do not edit */';

/** A named schema of the API, as opposed to an operation's `*Data`/`*Response`. */
const DTO_NAME = /(Dto|Request)$/;

/**
 * The DTO names `types.gen.ts` exports, sorted. The package root exports each
 * by name, so every consumer reads a wire shape from its one definition.
 */
function readDtoNames() {
  if (!fs.existsSync(generatedTypesPath)) {
    throw new Error(`No hey-api types at ${generatedTypesPath}; run openapi-ts first.`);
  }
  const generated = fs.readFileSync(generatedTypesPath, 'utf8');
  return Array.from(generated.matchAll(/^export type (\w+)\b/gm), (m) => m[1])
    .filter((name) => DTO_NAME.test(name))
    .sort();
}

/**
 * Keep the OpenAPI index.ts true to the tree: drop its model re-exports, so
 * consumers import DTOs from the package root instead; drop a re-export of a
 * schema file that no longer exists; and list exactly the service files there
 * are, so a feature that is pruned or added back takes its legacy services
 * in and out of it.
 */
function cleanIndexExports() {
  if (!fs.existsSync(indexFilePath)) {
    console.warn(`⚠️  index.ts not found at ${indexFilePath}. Skipping export cleanup.`);
    return;
  }

  const source = fs.readFileSync(indexFilePath, 'utf8');
  const lines = source.split(/\r?\n/);
  const target = (l) =>
    /^export\s+(?:type\s+)?\{[^}]*\}\s+from\s+['"](\.\/[^'"]+)['"]/.exec(l.trim())?.[1];

  const servicesDir = path.resolve(apiServicesFolder, 'services');
  const services = fs.existsSync(servicesDir)
    ? fs
        .readdirSync(servicesDir)
        .filter((f) => f.endsWith('.ts') && f !== 'index.ts')
        .map((f) => path.basename(f, '.ts'))
        .sort()
    : [];
  const serviceLines = services.map((name) => `export { ${name} } from './services/${name}';`);

  const kept = [];
  let servicesAt = -1;
  for (const line of lines) {
    const from = target(line);
    if (from?.startsWith('./services/')) {
      if (servicesAt === -1) servicesAt = kept.length;
      continue;
    }
    if (from?.startsWith('./models/')) continue;
    if (from && !fs.existsSync(path.resolve(apiServicesFolder, `${from}.ts`))) continue;
    kept.push(line);
  }
  if (servicesAt === -1) servicesAt = kept.length;
  kept.splice(servicesAt, 0, ...serviceLines);

  const result = kept.join('\n');
  if (result !== source) {
    fs.writeFileSync(indexFilePath, result);
    console.log('🧹  Brought the OpenAPI index.ts exports in line with the tree');
  }
}

/**
 * Generate a barrel index at services/index.ts re-exporting all service classes.
 */
function generateServicesIndex() {
  const servicesDir = path.resolve(apiServicesFolder, 'services');
  if (!fs.existsSync(servicesDir)) return;

  const serviceFiles = fs
    .readdirSync(servicesDir)
    .filter((f) => f.endsWith('.ts') && f !== 'index.ts');
  const exports = serviceFiles
    .map((f) => path.basename(f, '.ts'))
    .sort()
    .map((name) => `export { ${name} } from './${name}';`)
    .join('\n');

  fs.writeFileSync(path.join(servicesDir, 'index.ts'), `${BANNER}\n${exports}\n`);
  console.log('📄  Created services/index.ts');
}

/**
 * Generate the root src/index.ts barrel: the client configuration, the hey-api
 * SDK, the legacy services, and every DTO the API describes, by name, straight
 * from `generated/types.gen`. By name, not as a namespace: an
 * `export type * as` re-export does not survive the consumer's build, and a
 * bare `export type *` would also leak each operation's `*Data`/`*Response`.
 */
function generateRootIndex() {
  const rootIndexPath = path.resolve(__dirname, '../src/index.ts');

  const servicesDir = path.resolve(apiServicesFolder, 'services');
  const serviceFiles = fs.existsSync(servicesDir)
    ? fs.readdirSync(servicesDir).filter((f) => f.endsWith('.ts') && f !== 'index.ts')
    : [];

  const lines = [
    "export { applyApiClientConfig, getAuthHeaders, rememberHeaders } from './configure';",
    "export type { ApiClientConfig, AuthHeaders } from './configure';",
    "export { client as heyApiClient } from './generated/client.gen';",
    "export * as heyApiQuery from './generated/@tanstack/react-query.gen';",
    "export * as heyApiSdk from './generated/sdk.gen';",
    '',
    BANNER,
    '',
    '// Core',
    "export { ApiError } from './data-access/api/openapi/core/ApiError';",
    "export { CancelablePromise, CancelError } from './data-access/api/openapi/core/CancelablePromise';",
    "export { OpenAPI } from './data-access/api/openapi/core/OpenAPI';",
    "export type { OpenAPIConfig } from './data-access/api/openapi/core/OpenAPI';",
    '',
    '// Services',
    ...serviceFiles.map((f) => {
      const name = path.basename(f, '.ts');
      return `export { ${name} } from './data-access/api/openapi/services/${name}';`;
    }),
    '',
    '// DTOs',
    `export type {\n${readDtoNames()
      .map((name) => `  ${name},`)
      .join('\n')}\n} from './generated/types.gen';`,
    '',
  ];

  fs.writeFileSync(rootIndexPath, lines.join('\n'));
  console.log(`📄  Created ${path.relative(process.cwd(), rootIndexPath)}`);
}

/**
 * Bring the two barrels Biome checks to what `pnpm check` accepts.
 *
 * `src/index.ts` and `src/generated/index.ts` are the only files here Biome
 * does not ignore (`biome.json` skips `*.gen.ts` and `src/data-access`), and it holds them to its import order as well as its
 * format. Formatting alone left them in an order `pnpm check` rewrites, so a
 * second `pnpm generate:api-client` produced a diff; `check --write` applies
 * both, which keeps the command idempotent.
 */
function formatFiles() {
  try {
    const rootIndex = path.resolve(__dirname, '../src/index.ts');
    const generatedIndex = path.resolve(__dirname, '../src/generated/index.ts');
    execSync(`npx biome check --write "${rootIndex}" "${generatedIndex}"`, {
      stdio: 'inherit',
    });
  } catch (e) {
    console.warn('Formatting skipped (biome not available):', e.message);
  }
}

function main() {
  cleanIndexExports();
  generateServicesIndex();
  generateRootIndex();
  formatFiles();
  console.log('✨  OpenAPI Post-Process Done');
}

main();
