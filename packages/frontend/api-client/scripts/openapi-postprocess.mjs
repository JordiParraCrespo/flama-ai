import { execSync } from 'node:child_process';
import * as fs from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const apiServicesFolder = path.resolve(__dirname, '../src/data-access/api/openapi');
const commonDir = path.resolve(__dirname, '../src/common');
const destModelsDir = path.resolve(commonDir, 'models');
const indexFilePath = path.join(apiServicesFolder, 'index.ts');
const commonIndexPath = path.join(commonDir, 'index.ts');
const generatedTypesPath = path.resolve(__dirname, '../src/generated/types.gen.ts');

const BANNER = '/* Auto-generated by openapi-postprocess -- do not edit */';

/** A named schema of the API, as opposed to an operation's `*Data`/`*Response`. */
const DTO_NAME = /(Dto|Request)$/;

/** Every type `types.gen.ts` exports, or null when there is no hey-api output. */
function readGeneratedNames() {
  if (!fs.existsSync(generatedTypesPath)) return null;
  const generated = fs.readFileSync(generatedTypesPath, 'utf8');
  return new Set(Array.from(generated.matchAll(/^export type (\w+)\b/gm), (m) => m[1]));
}

/**
 * One generator owns every DTO name, and `src/common/models/` follows it.
 *
 * `src/common/models/` was emitted by openapi-typescript-codegen, which is
 * retired: `openapi-ts` now writes the whole surface to `src/generated/`. Two
 * definitions of the same name silently drift — a DTO gains a property in the
 * API and only the hey-api copy learns about it, while consumers that import
 * the name from this package keep the stale shape. So every file here is a
 * one-line re-export of the hey-api type of the same name, one per DTO the API
 * describes, leaving one definition per name.
 *
 * The directory tracks the API both ways, which is what a feature's
 * `regenerate` step relies on: `pnpm starter:prune --without organizations`
 * drops the organization DTOs from the API, and their re-exports go with them
 * (the feature's `paths` take the legacy services that imported them); a
 * plugin that brings the feature back brings them back. A hand-written model
 * with no hey-api counterpart is kept and reported rather than failing the
 * build; delete it, with its schema and service, alongside the endpoint.
 */
function syncModels() {
  const generatedNames = readGeneratedNames();
  if (!generatedNames) {
    console.warn(
      `⚠️  No hey-api types at ${generatedTypesPath}. Leaving src/common/models untouched.`,
    );
    return;
  }

  fs.mkdirSync(destModelsDir, { recursive: true });
  const existing = fs
    .readdirSync(destModelsDir)
    .filter((f) => f.endsWith('.ts'))
    .map((f) => path.basename(f, '.ts'));
  const wanted = new Set([
    ...[...generatedNames].filter((name) => DTO_NAME.test(name)),
    ...existing.filter((name) => generatedNames.has(name)),
  ]);

  const specifier = path
    .relative(destModelsDir, generatedTypesPath)
    .replace(/\\/g, '/')
    .replace(/\.ts$/, '');

  const orphans = [];
  const removed = [];
  let written = 0;

  for (const name of existing) {
    if (wanted.has(name)) continue;
    const fullPath = path.join(destModelsDir, `${name}.ts`);
    if (fs.readFileSync(fullPath, 'utf8').startsWith(BANNER)) {
      fs.rmSync(fullPath);
      removed.push(name);
    } else {
      orphans.push(name);
    }
  }

  for (const name of [...wanted].sort()) {
    const fullPath = path.join(destModelsDir, `${name}.ts`);
    const contents = `${BANNER}\nexport type { ${name} } from '${specifier}';\n`;
    if (!fs.existsSync(fullPath) || fs.readFileSync(fullPath, 'utf8') !== contents) {
      fs.writeFileSync(fullPath, contents);
      written += 1;
    }
  }

  console.log(
    `🔁  ${wanted.size} model(s) re-export ${path.basename(generatedTypesPath)}, ${written} written`,
  );

  if (removed.length > 0) {
    console.warn(
      `🗑️  ${removed.length} re-export(s) removed, their DTO is no longer in apps/api/openapi.json:\n` +
        removed.map((name) => `      - ${name}`).join('\n'),
    );
  }

  if (orphans.length > 0) {
    console.warn(
      `⚠️  ${orphans.length} legacy model(s) have no hey-api counterpart and keep their own definition:\n` +
        orphans.map((name) => `      - ${name}`).join('\n') +
        '\n    They are not in apps/api/openapi.json, so nothing regenerates them.',
    );
  }
}

/**
 * Fix import paths in generated service files so they reference
 * the models from their new location in src/common/models.
 */
function fixImports() {
  const servicesDir = path.resolve(apiServicesFolder, 'services');
  if (!fs.existsSync(servicesDir)) {
    console.warn('⚠️  Services directory not found. Skipping import fixes.');
    return;
  }

  const filenames = fs.readdirSync(servicesDir);
  for (const filename of filenames) {
    const fullPath = path.join(servicesDir, filename);
    if (!fs.lstatSync(fullPath).isFile()) continue;

    const src = fs.readFileSync(fullPath, 'utf8');
    const dst = src.replace(/(['"])(?:\.\.\/)+models\//g, '$1../../../../common/models/');

    if (dst !== src) {
      fs.writeFileSync(fullPath, dst);
      console.log(`🔧  Fixed imports in ${filename}`);
    }
  }
}

/**
 * Generate a barrel index file at src/common/index.ts that
 * re-exports every model type.
 */
function generateCommonIndex() {
  if (!fs.existsSync(destModelsDir)) {
    console.warn('⚠️  No models found to index. Skipping common index generation.');
    return;
  }

  const modelFiles = fs.readdirSync(destModelsDir).filter((f) => f.endsWith('.ts'));

  const exports = modelFiles
    .map((f) => path.basename(f, '.ts'))
    .sort()
    .map((name) => `export type { ${name} } from "./models/${name}";`)
    .join('\n');

  fs.writeFileSync(commonIndexPath, `${BANNER}\n${exports}\n`);
  console.log(`📄  Created ${path.relative(process.cwd(), commonIndexPath)}`);
}

/**
 * Keep the OpenAPI index.ts true to the tree: drop its model re-exports, so
 * consumers import models from src/common instead; drop a re-export of a
 * schema file that no longer exists; and list exactly the service files there
 * are, so a feature that is pruned or added back takes its legacy services
 * in and out of it.
 */
function cleanIndexExports() {
  if (!fs.existsSync(indexFilePath)) {
    console.warn(`⚠️  index.ts not found at ${indexFilePath}. Skipping export cleanup.`);
    return;
  }

  const source = fs.readFileSync(indexFilePath, 'utf8');
  const lines = source.split(/\r?\n/);
  const target = (l) =>
    /^export\s+(?:type\s+)?\{[^}]*\}\s+from\s+['"](\.\/[^'"]+)['"]/.exec(l.trim())?.[1];

  const servicesDir = path.resolve(apiServicesFolder, 'services');
  const services = fs.existsSync(servicesDir)
    ? fs
        .readdirSync(servicesDir)
        .filter((f) => f.endsWith('.ts') && f !== 'index.ts')
        .map((f) => path.basename(f, '.ts'))
        .sort()
    : [];
  const serviceLines = services.map((name) => `export { ${name} } from './services/${name}';`);

  const kept = [];
  let servicesAt = -1;
  for (const line of lines) {
    const from = target(line);
    if (from?.startsWith('./services/')) {
      if (servicesAt === -1) servicesAt = kept.length;
      continue;
    }
    if (from?.startsWith('./models/')) continue;
    if (from && !fs.existsSync(path.resolve(apiServicesFolder, `${from}.ts`))) continue;
    kept.push(line);
  }
  if (servicesAt === -1) servicesAt = kept.length;
  kept.splice(servicesAt, 0, ...serviceLines);

  const result = kept.join('\n');
  if (result !== source) {
    fs.writeFileSync(indexFilePath, result);
    console.log('🧹  Brought the OpenAPI index.ts exports in line with the tree');
  }
}

/**
 * Generate a barrel index at services/index.ts re-exporting all service classes.
 */
function generateServicesIndex() {
  const servicesDir = path.resolve(apiServicesFolder, 'services');
  if (!fs.existsSync(servicesDir)) return;

  const serviceFiles = fs
    .readdirSync(servicesDir)
    .filter((f) => f.endsWith('.ts') && f !== 'index.ts');
  const exports = serviceFiles
    .map((f) => path.basename(f, '.ts'))
    .sort()
    .map((name) => `export { ${name} } from './${name}';`)
    .join('\n');

  fs.writeFileSync(path.join(servicesDir, 'index.ts'), `${BANNER}\n${exports}\n`);
  console.log('📄  Created services/index.ts');
}

/**
 * Generate the root src/index.ts barrel that re-exports core, services, and models.
 */
function generateRootIndex() {
  const rootIndexPath = path.resolve(__dirname, '../src/index.ts');

  const servicesDir = path.resolve(apiServicesFolder, 'services');
  const serviceFiles = fs.existsSync(servicesDir)
    ? fs.readdirSync(servicesDir).filter((f) => f.endsWith('.ts') && f !== 'index.ts')
    : [];

  const modelFiles = fs.existsSync(destModelsDir)
    ? fs.readdirSync(destModelsDir).filter((f) => f.endsWith('.ts'))
    : [];

  // Every DTO the API describes is a file in `src/common/models` (see
  // `syncModels`), including those of endpoints the retired generator never
  // covered, so each is exported here by name and no consumer hand-writes a
  // wire shape. By name, not as a namespace: an `export type * as` re-export
  // does not survive the consumer's build, and the failure is silent — the
  // member resolves to something unusable rather than erroring at the import.
  const lines = [
    "export { applyApiClientConfig, getAuthHeaders, rememberHeaders } from './configure';",
    "export type { ApiClientConfig, AuthHeaders } from './configure';",
    "export { client as heyApiClient } from './generated/client.gen';",
    "export * as heyApiQuery from './generated/@tanstack/react-query.gen';",
    "export * as heyApiSdk from './generated/sdk.gen';",
    '',
    BANNER,
    '',
    '// Core',
    "export { ApiError } from './data-access/api/openapi/core/ApiError';",
    "export { CancelablePromise, CancelError } from './data-access/api/openapi/core/CancelablePromise';",
    "export { OpenAPI } from './data-access/api/openapi/core/OpenAPI';",
    "export type { OpenAPIConfig } from './data-access/api/openapi/core/OpenAPI';",
    '',
    '// Services',
    ...serviceFiles.map((f) => {
      const name = path.basename(f, '.ts');
      return `export { ${name} } from './data-access/api/openapi/services/${name}';`;
    }),
    '',
    '// Models',
    ...modelFiles.map((f) => {
      const name = path.basename(f, '.ts');
      return `export type { ${name} } from './common/models/${name}';`;
    }),
    '',
  ];

  fs.writeFileSync(rootIndexPath, lines.join('\n'));
  console.log(`📄  Created ${path.relative(process.cwd(), rootIndexPath)}`);
}

/**
 * Bring the two barrels Biome checks to what `pnpm check` accepts.
 *
 * `src/index.ts` and `src/generated/index.ts` are the only files here Biome
 * does not ignore (`biome.json` skips `*.gen.ts`, `src/common` and
 * `src/data-access`), and it holds them to its import order as well as its
 * format. Formatting alone left them in an order `pnpm check` rewrites, so a
 * second `pnpm generate:api-client` produced a diff; `check --write` applies
 * both, which keeps the command idempotent.
 */
function formatFiles() {
  try {
    const rootIndex = path.resolve(__dirname, '../src/index.ts');
    const generatedIndex = path.resolve(__dirname, '../src/generated/index.ts');
    execSync(`npx biome check --write "${rootIndex}" "${generatedIndex}"`, {
      stdio: 'inherit',
    });
  } catch (e) {
    console.warn('Formatting skipped (biome not available):', e.message);
  }
}

function main() {
  syncModels();
  fixImports();
  generateCommonIndex();
  cleanIndexExports();
  generateServicesIndex();
  generateRootIndex();
  formatFiles();
  console.log('✨  OpenAPI Post-Process Done');
}

main();
